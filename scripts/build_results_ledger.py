#!/usr/bin/env python3
"""Regenerate docs/results.md from per-run report files.

Why this exists: a single hand-edited Markdown table is a merge-conflict magnet
when three agents append rows concurrently. Each run instead owns one directory,

    results/<experiment-id>/<run-id>/report.md

with a YAML front-matter block carrying the ledger fields. This script collects
them and rewrites the ledger table. The ledger is generated output: edit the run
reports, never the table.

A run report's front matter must contain:
    experiment, run_id, candidate, baseline, split_axis, quality,
    resource_cost, status

Optional:
    evidence (path or URI), claim_level, date

Usage:
    python3 scripts/build_results_ledger.py            # rewrite the ledger
    python3 scripts/build_results_ledger.py --check    # fail if out of date
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

REQUIRED = (
    "experiment",
    "run_id",
    "candidate",
    "baseline",
    "split_axis",
    "quality",
    "resource_cost",
    "status",
)

HEADER = """# Results ledger

Generated by `scripts/build_results_ledger.py` from `results/<experiment>/<run-id>/report.md`.
Do not edit this table by hand; edit the run report and regenerate.

Published papers and historical results from other projects are not entries in
this ledger. Record failed and inconclusive runs alongside successful ones.
Never overwrite a result when a scorer or protocol changes: add a new run report
with its own ID and provenance.

| Experiment/run | Candidate / baseline | Split / task axis | Quality and uncertainty | Total resource cost | Evidence | Status / decision |
|---|---|---|---|---|---|---|
"""

EMPTY_NOTE = "\nNo experiment runs have been recorded yet.\n"


def parse_front_matter(text: str) -> dict[str, str] | None:
    """Minimal YAML front-matter reader: flat `key: value` pairs only.

    Avoids a PyYAML dependency for a format we fully control. Returns None when
    the file has no front-matter block.
    """
    lines = text.splitlines()
    if not lines or lines[0].strip() != "---":
        return None
    fields: dict[str, str] = {}
    for line in lines[1:]:
        if line.strip() == "---":
            return fields
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        if ":" not in line:
            continue
        key, _, value = line.partition(":")
        fields[key.strip()] = value.strip().strip('"').strip("'")
    return None  # unterminated block


def escape_cell(value: str) -> str:
    return value.replace("|", "\\|").replace("\n", " ").strip()


def collect(root: Path) -> tuple[list[dict[str, str]], list[str]]:
    rows: list[dict[str, str]] = []
    errors: list[str] = []
    results_dir = root / "results"
    if not results_dir.is_dir():
        return rows, errors

    for report in sorted(results_dir.glob("*/*/report.md")):
        rel = report.relative_to(root)
        fields = parse_front_matter(report.read_text(encoding="utf-8"))
        if fields is None:
            errors.append(f"{rel}: missing or unterminated YAML front matter")
            continue
        missing = [k for k in REQUIRED if not fields.get(k)]
        if missing:
            errors.append(f"{rel}: missing required field(s): {', '.join(missing)}")
            continue
        fields["_path"] = str(rel)
        rows.append(fields)

    rows.sort(key=lambda r: (r["experiment"], r["run_id"]))
    return rows, errors


def render(rows: list[dict[str, str]]) -> str:
    if not rows:
        return HEADER + EMPTY_NOTE
    body = []
    for r in rows:
        # The ledger lives in docs/, so a repo-root-relative report path must be
        # rewritten as ../results/... or the Markdown link resolves to
        # docs/results/... and breaks. scripts/check_docs.py catches this.
        report_link = f"../{r['_path']}"
        evidence = r.get("evidence")
        cells = [
            f"{r['experiment']} / {r['run_id']}",
            f"{r['candidate']} vs {r['baseline']}",
            r["split_axis"],
            r["quality"],
            r["resource_cost"],
            f"[report]({report_link})" + (f" · {evidence}" if evidence else ""),
            r["status"],
        ]
        body.append("| " + " | ".join(escape_cell(c) for c in cells) + " |")
    return HEADER + "\n".join(body) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default=".", help="repository root (default: .)")
    parser.add_argument(
        "--check",
        action="store_true",
        help="do not write; exit 1 if the ledger is stale or a report is invalid",
    )
    args = parser.parse_args()

    root = Path(args.root).resolve()
    rows, errors = collect(root)

    if errors:
        print("build_results_ledger: invalid run report(s):")
        for err in errors:
            print(f"  - {err}")
        return 1

    ledger = root / "docs" / "results.md"
    rendered = render(rows)
    current = ledger.read_text(encoding="utf-8") if ledger.exists() else ""

    if args.check:
        if current != rendered:
            print(
                "build_results_ledger: docs/results.md is out of date.\n"
                "Run: python3 scripts/build_results_ledger.py"
            )
            return 1
        print(f"build_results_ledger: ledger current ({len(rows)} run(s))")
        return 0

    ledger.parent.mkdir(parents=True, exist_ok=True)
    ledger.write_text(rendered, encoding="utf-8")
    print(f"build_results_ledger: wrote docs/results.md ({len(rows)} run(s))")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
